using Microsoft.EntityFrameworkCore;

namespace Wattzicht.Api.Data;

/// <summary>
/// Kleine, idempotente schema-aanpassingen voor databases die al met EnsureCreated zijn aangemaakt.
/// EnsureCreated doet niets als de database al bestaat; deze stappen voegen nieuwe kolommen en tabellen toe.
/// Elke stap mag vaker draaien. Vervang dit door EF-migraties zodra die in de repo staan.
/// </summary>
public static class SchemaUpgrades
{
    private static readonly string[] Steps =
    [
        // 2026-10: toestemming bewoner voor meekijken door de installateur (standaard uit).
        """ALTER TABLE households ADD COLUMN IF NOT EXISTS "InstallerAccessGranted" boolean NOT NULL DEFAULT false""",
        """ALTER TABLE households ADD COLUMN IF NOT EXISTS "InstallerAccessChangedAt" timestamp with time zone NULL""",

        // 2026-10: logboek van inzage door de installateur.
        """
        CREATE TABLE IF NOT EXISTS installer_access_log (
            "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "HouseholdId" uuid NOT NULL REFERENCES households ("Id") ON DELETE CASCADE,
            "InstallerId" uuid NOT NULL,
            "UserId" uuid NOT NULL,
            "Action" character varying(40) NOT NULL,
            "At" timestamp with time zone NOT NULL
        )
        """,
        """CREATE INDEX IF NOT EXISTS ix_installer_access_log_household_at ON installer_access_log ("HouseholdId", "At")""",

        // 2026-10: pushmeldingen.
        """ALTER TABLE households ADD COLUMN IF NOT EXISTS "NotifyAlerts" boolean NOT NULL DEFAULT true""",
        """ALTER TABLE households ADD COLUMN IF NOT EXISTS "NotifySurplus" boolean NOT NULL DEFAULT true""",
        """ALTER TABLE households ADD COLUMN IF NOT EXISTS "LastSurplusPushAt" timestamp with time zone NULL""",
        """ALTER TABLE households ADD COLUMN IF NOT EXISTS "LastAlertPushAt" timestamp with time zone NULL""",
        """
        CREATE TABLE IF NOT EXISTS push_devices (
            "Id" uuid NOT NULL PRIMARY KEY,
            "HouseholdId" uuid NOT NULL REFERENCES households ("Id") ON DELETE CASCADE,
            "Token" character varying(4096) NOT NULL,
            "Platform" character varying(20) NOT NULL,
            "CreatedAt" timestamp with time zone NOT NULL,
            "LastSeenAt" timestamp with time zone NOT NULL
        )
        """,
        """CREATE UNIQUE INDEX IF NOT EXISTS ix_push_devices_token ON push_devices ("Token")""",
        """CREATE INDEX IF NOT EXISTS ix_push_devices_household ON push_devices ("HouseholdId")""",

        // 2026-10: terugleverkosten van de leverancier per kWh.
        """ALTER TABLE tariffs ADD COLUMN IF NOT EXISTS "FeedInCostPerKwh" numeric(10,4) NOT NULL DEFAULT 0""",
    ];

    public static async Task ApplyAsync(AppDbContext db, CancellationToken ct = default)
    {
        foreach (var sql in Steps)
        {
            await db.Database.ExecuteSqlRawAsync(sql, ct);
        }
    }
}
